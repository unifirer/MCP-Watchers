# 1. Behaviour: the incremental log tail
# ---------------------------------------------------------------------------


def _tail(path, offset, backlog=65536):
    return watcher_log_tail.read_watcher_log_tail(str(path), offset, backlog)


def test_missing_file_leaves_the_offset_untouched(tmp_path):
    result = _tail(tmp_path / "nope.log", 42)
    assert result.lines == ()
    assert result.offset == 42
    assert result.rotated is False


def test_reads_only_the_appended_bytes(tmp_path):
    log = tmp_path / "w.log"
    log.write_bytes(b"alpha\nbeta\ngamma")
    first = _tail(log, 0)
    assert first.lines == ("alpha", "beta", "gamma")
    assert first.offset == len(b"alpha\nbeta\ngamma")
    assert first.rotated is False

    # Nothing new: same offset, no lines, no rotation.
    second = _tail(log, first.offset)
    assert second.lines == ()
    assert second.offset == first.offset
    assert second.rotated is False


def test_unterminated_final_line_is_displayed(tmp_path):
    """repowise writes its final "N changed file(s)" line with NO trailing CR/LF.
    Suppressing unterminated lines would hide that change-event line forever."""
    log = tmp_path / "w.log"
    log.write_bytes(b"header\n3 changed file(s)")
    result = _tail(log, 0)
    assert result.lines == ("header", "3 changed file(s)")


def test_leading_newline_of_a_delta_yields_an_empty_line(tmp_path):
    """Faithful quirk of the original, not a new bug: the newline that terminated
    the PREVIOUS read is part of the next delta, so it splits to a leading ''."""
    log = tmp_path / "w.log"
    log.write_bytes(b"a\nb")
    first = _tail(log, 0)
    assert first.lines == ("a", "b")

    with open(log, "ab") as fh:
        fh.write(b"\nc\n")
    second = _tail(log, first.offset)
    assert second.lines == ("", "c")


def test_crlf_is_split(tmp_path):
    log = tmp_path / "w.log"
    log.write_bytes(b"a\r\nb\r\n")
    assert _tail(log, 0).lines == ("a", "b")


def test_utf8_bom_is_skipped_only_at_offset_zero(tmp_path):
    log = tmp_path / "w.log"
    log.write_bytes(b"\xef\xbb\xbfx\ny")
    assert _tail(log, 0).lines == ("x", "y")


def test_truncation_reports_rotation_and_reseats(tmp_path):
    log = tmp_path / "w.log"
    log.write_bytes(b"z" * 100)
    assert _tail(log, 100).offset == 100

    log.write_bytes(b"fresh\n")  # truncated to 6 bytes
    result = _tail(log, 100)
    assert result.rotated is True
    assert result.offset == len(b"fresh\n")
    assert result.lines == ("fresh",)


def test_reseat_keeps_a_bounded_backlog(tmp_path):
    log = tmp_path / "w.log"
    log.write_bytes(b"x" * 1000)
    log.write_bytes(b"y" * 100)  # shrink, then ask for a 50-byte backlog
    result = _tail(log, 1000, backlog=50)
    assert result.rotated is True
    assert result.offset == 100
    assert result.lines == ("y" * 50,)


def test_malformed_bytes_are_replaced_not_raised(tmp_path):
    """A torn multi-byte write must not crash the tailer. The .ps1 decoder
    replaces malformed sequences with U+FFFD; so does this one."""
    log = tmp_path / "w.log"
    log.write_bytes(b"ok\n\xff\xfe bad\n")
    result = _tail(log, 0)
    assert result.lines[0] == "ok"
    assert "\ufffd" in result.lines[1]


