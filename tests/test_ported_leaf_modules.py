def test_sweep_match_matches_ps1_vectors():
    for command_line, pattern, expected in SWEEP_MATCH_VECTORS:
        actual = watcher_patterns.test_watcher_sweep_match(command_line, pattern)
        assert actual is expected, (
            f"test_watcher_sweep_match({command_line!r}, {pattern!r}) "
            f"returned {actual}, .ps1 returned {expected}"
        )


def test_empty_pattern_is_match_all_but_never_an_empty_command_line():
    match_all = [e for e in watcher_patterns.WATCHER_SWEEP_PATTERNS if e.pattern == ""]
    assert match_all, "expected match-all entries (graphify-rs rebuild children)"
    assert watcher_patterns.test_watcher_sweep_match("anything", "") is True
    assert watcher_patterns.test_watcher_sweep_match("", "") is False
    assert watcher_patterns.test_watcher_sweep_match(None, "") is False


