"""Acceptance suite for the first ported leaf modules - bead mcpw-xeu.2.

The Python modules under Modules\\*.py are ports of live PowerShell modules. The
PowerShell originals are STILL the ones the launcher and the generated pane
scripts use, so for now each piece of logic has two representations. This suite
therefore does two separate jobs:

  1. BEHAVIOUR - exercises the Python modules directly, by importing them. This
     is the point of porting: the PowerShell suites for the same logic have to
     slice source text out of a .ps1 by string anchor and Invoke-Expression it
     (38 Get-Content -Raw and 31 Invoke-Expression across tests\\). That technique
     breaks silently when an anchor drifts - see mcpw-d76 for one found in the
     wild. A real import cannot drift.

  2. EQUIVALENCE - pins the Python modules against vectors generated by RUNNING
     the .ps1 on 2026-09-23, and re-parses the sweep table out of
     watcher_patterns.ps1 on every run. Without this, porting a safety-critical
     table and an attribution gate would create a silent drift path: the sweep
     would keep "working" while matching the wrong processes.

The pinned vectors are real outputs, not hand-written expectations. Regenerate
them by dot-sourcing Modules\\watcher_workspace.ps1 and Modules\\watcher_patterns.ps1
and calling the functions - do not edit a vector to make a test pass.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from Modules import watcher_log_tail, watcher_patterns, watcher_workspace  # noqa: E402

PATTERNS_PS1 = ROOT / "Modules" / "watcher_patterns.ps1"
WORKSPACE_PS1 = ROOT / "Modules" / "watcher_workspace.ps1"
LOG_TAIL_PS1 = ROOT / "Modules" / "watcher_log_tail.ps1"

# ---------------------------------------------------------------------------
# 2. Equivalence: the sweep table
# ---------------------------------------------------------------------------

_ENTRY = re.compile(
    r"@\{\s*Name\s*=\s*'([^']*)'\s*;\s*Pattern\s*=\s*'([^']*)'\s*"
    r"(?:[;,]\s*Persistent\s*=\s*(\$true))?\s*\}"
)


def _ps1_sweep_table():
    src = PATTERNS_PS1.read_text(encoding="utf-8")
    entries = _ENTRY.findall(src)
    assert entries, "parsed no sweep entries out of watcher_patterns.ps1"
    return [(name, pattern, persistent == "$true") for name, pattern, persistent in entries]


def test_sweep_table_matches_ps1_exactly():
    """The ported table must equal the .ps1 table: same entries, same order."""
    assert _ps1_sweep_table() == [
        (entry.name, entry.pattern, entry.persistent)
        for entry in watcher_patterns.WATCHER_SWEEP_PATTERNS
    ], (
        "Modules/watcher_patterns.py and Modules/watcher_patterns.ps1 disagree. "
        "The sweep table is the single source of truth for teardown; fix the "
        "divergence before either side is used."
    )


def test_persistent_flags_are_carried():
    """`Persistent = $true` marks singletons that must never be swept on takeover."""
    persistent = {
        entry.name for entry in watcher_patterns.WATCHER_SWEEP_PATTERNS if entry.persistent
    }
    # claude-mcp.exe, node.exe claude-mcp-server, python.exe mcp_agent_mail,
    # python.exe embed_server. The mail and embed singletons are shared with
    # sibling checkouts - see mcpw-xeu.9.
    assert len([e for e in watcher_patterns.WATCHER_SWEEP_PATTERNS if e.persistent]) == 4
    assert "python.exe" in persistent


