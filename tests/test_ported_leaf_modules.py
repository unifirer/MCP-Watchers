    ("node.exe C:\\x\\heimdall.js mcp", "heimdall.js daemon", False),
    # PowerShell -match is case-insensitive; this vector is what proves the port
    # reproduces that rather than doing a case-sensitive compare.
    (
        "PS -File C:\\TEMP\\VAD-WATCHERS\\77442B14\\PANES\\TAIL_GREPAI.PS1",
        "panes\\tail_",
        True,
    ),
