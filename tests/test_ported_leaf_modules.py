# 2. Equivalence: process attribution
# ---------------------------------------------------------------------------

KEY_THIS = "77442b14"
ROOT_THIS = "J:\\audio\\MCP-Watchers"

# (command_line, key, root, expected) - generated by running
# Test-WatchersProcessAttribution in the live .ps1.
ATTRIBUTION_VECTORS = [
    ("ps -File C:\\Temp\\vad-watchers\\77442b14\\panes\\tail_grepai.ps1", KEY_THIS, ROOT_THIS, True),
    ("cmd --repo j:\\AUDIO\\vad", KEY_THIS, ROOT_THIS, False),
    ("cmd -c C:\\anything", KEY_THIS, ROOT_THIS, False),
    ("", KEY_THIS, ROOT_THIS, False),
    ("cmd", "", "", False),
    # ordinal-ignore-case on the root marker
    ("cmd -File J:\\AUDIO\\MCP-WATCHERS\\x", KEY_THIS, ROOT_THIS, True),
    # the 4-character floor on the root marker: both sides of the boundary, with
    # a root that IS contained in the command line, so only length decides.
    ("cmd -c C:\\ab", "", "C:\\", False),
    ("cmd -c C:\\ab", "", "C:\\a", True),
]


def test_attribution_matches_ps1_vectors():
    for command_line, key, root, expected in ATTRIBUTION_VECTORS:
        actual = watcher_workspace.test_watchers_process_attribution(command_line, key, root)
        assert actual is expected, (
            f"test_watchers_process_attribution({command_line!r}, {key!r}, {root!r}) "
            f"returned {actual}, .ps1 returned {expected}"
        )


def test_attribution_fails_safe_on_unattributable_process():
    """No marker means never terminate: skipping an orphan is harmless, killing a
    sibling repository's watcher is not."""
    assert watcher_workspace.test_watchers_process_attribution("cmd /c whatever", "", "") is False
    assert watcher_workspace.test_watchers_process_attribution(None, KEY_THIS, ROOT_THIS) is False


def test_short_workspace_root_is_ignored():
    """A drive root such as C:\\ would attribute every process on the machine.

    Vectors generated by running the .ps1 with the SAME command line and two
    roots one character apart, so length is the only variable: len('C:\\') == 3
    is refused, len('C:\\a') == 4 is accepted.
    """
    assert watcher_workspace.test_watchers_process_attribution("cmd -c C:\\ab", "", "C:\\") is False
    assert watcher_workspace.test_watchers_process_attribution("cmd -c C:\\ab", "", "C:\\a") is True
    # ...and a long-enough root that simply is not in the command line still fails
    assert watcher_workspace.test_watchers_process_attribution("cmd -c C:\\ab", "", "C:\\zz") is False


